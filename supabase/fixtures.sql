-- Permanent archive for Persibo fixtures and match results.
-- Run this script once in Supabase SQL Editor.
create table if not exists public.fixtures (
    id bigint generated by default as identity primary key,
    match_url text not null unique,
    raw text not null default '',
    date text not null default '',
    date_iso text not null default '',
    time text not null default '',
    home text not null default '',
    away text not null default '',
    opponent text not null default '',
    venue text not null default '',
    score text not null default '',
    status text not null default 'Terjadwal',
    matchweek integer,
    source text not null default 'ileague',
    manual_override boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.fixtures add column if not exists manual_override boolean not null default false;

create index if not exists fixtures_date_iso_idx on public.fixtures (date_iso);
create index if not exists fixtures_status_idx on public.fixtures (status);

create or replace function public.set_fixtures_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists fixtures_updated_at on public.fixtures;
create trigger fixtures_updated_at
before update on public.fixtures
for each row execute function public.set_fixtures_updated_at();

-- Keep browser access closed. The backend accesses this table with the
-- SUPABASE_SERVICE_ROLE_KEY stored only in server-side environment variables.
alter table public.fixtures enable row level security;
